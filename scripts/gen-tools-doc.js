// Regenerates TOOLS.md from the catalogue:  node scripts/gen-tools-doc.js
import { writeFileSync } from "node:fs";
import { ALL_SPECS, ALL_CUSTOM, BUILTIN, TOOLSETS } from "../src/tools/index.js";

const by = {};
for (const t of [...ALL_SPECS, ...ALL_CUSTOM]) (by[t.toolset] ||= []).push(t);
const total = BUILTIN.length + ALL_SPECS.length + ALL_CUSTOM.length;
let md = `# Tools (${total})\n\nGenerated by \`node scripts/gen-tools-doc.js\`. Toolsets can be switched with the \`GITHUB_TOOLSETS\` env var\n(\`all\` by default; e.g. \`repos,git,issues,pulls\` or \`all,-codespaces,-packages\`). The core tools below are always on.\n\n`;
md += `## core (always on)\n\n${BUILTIN.map((n) => `- \`${n}\``).join("\n")}\n\n`;
for (const ts of TOOLSETS) {
  md += `## ${ts} (${by[ts].length})\n\n`;
  for (const t of by[ts].sort((a, b) => a.name.localeCompare(b.name))) md += `- \`${t.name}\` — ${t.description.replace(/\|/g, "\\|")}\n`;
  md += "\n";
}
writeFileSync(new URL("../TOOLS.md", import.meta.url), md);
console.log(`TOOLS.md written (${total} tools)`);
